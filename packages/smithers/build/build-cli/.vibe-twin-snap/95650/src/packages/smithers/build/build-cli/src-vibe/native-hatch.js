// E-7: preserve the native host primitives used by plain synchronous APIs.
import * as NodePath from "node:path";
import * as NodeFs from "node:fs";
import * as NodeUtil from "node:util/types";
import * as Os from "node:os";
import { createHash } from "node:crypto";
import { StringDecoder } from "node:string_decoder";
import { stripVTControlCharacters } from "node:util";
import { Writable } from "node:stream";
export const isAbsolute = (path) => NodePath.isAbsolute(path);
export const resolve = (...paths) => NodePath.resolve(...paths);
export const relative = (from, to) => NodePath.relative(from, to);
export const basename = (path) => NodePath.basename(path);
export const join = (...paths) => NodePath.join(...paths);
export const isProxy = (value) => NodeUtil.isProxy(value);
export const isNativeError = (value) => NodeUtil.isNativeError(value);
export const readText = (path, encoding) => NodeFs.readFileSync(path, encoding);
export const appendText = (path, text, encoding) => NodeFs.appendFileSync(path, text, encoding);
export const hash = (algorithm, options) => createHash(algorithm, options);
export const processEnvironment = () => process.env;
export const stdin = () => process.stdin;
export const stdout = () => process.stdout;
export const stderr = () => process.stderr;
export const parallelism = () => Os.availableParallelism();
export const byteLength = (value, encoding) => Buffer.byteLength(value, encoding);
export const hex = (value) => Buffer.from(value).toString("hex");
export const strip = (text) => stripVTControlCharacters(text);
export const decoder = (encoding) => new StringDecoder(encoding);
export const writable = (options) => new Writable(options);
export const interval = (tick, delay) => setInterval(tick, delay);
export const clear = (timer) => clearInterval(timer);
export const onExit = (listener) => { process.once("exit", listener); };
export const removeExit = (listener) => { process.removeListener("exit", listener); };
