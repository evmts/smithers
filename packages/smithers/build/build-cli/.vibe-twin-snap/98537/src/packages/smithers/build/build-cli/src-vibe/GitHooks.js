/**
 * One typed git-hooks refusal.
 *
 * @category errors
 * @since 0.1.0
 */
export class GitHooksError extends Data.TaggedError("smithers-build/GitHooksError") {
    constructor(code, message) {
        super({ code, message: `${code}: ${message}` });
    }
}
/**
 * Checks whether a value is a git-hooks refusal.
 *
 * @category guards
 * @since 0.1.0
 */
export const isGitHooksError = (value) => value instanceof GitHooksError;
/**
 * The workspace hook event names, in render order.
 *
 * @category constants
 * @since 0.1.0
 */
export const hookNames = ["preCommit", "postCommit", "prePush", "postMerge"];
/**
 * The git hook file each workspace event installs to.
 *
 * @category constants
 * @since 0.1.0
 */
export const hookFiles = Object.freeze({
    preCommit: "pre-commit",
    postCommit: "post-commit",
    prePush: "pre-push",
    postMerge: "post-merge"
});
/**
 * The exact label grammar a rendered script may carry: one shell word.
 *
 * @category constants
 * @since 0.1.0
 */
export const labelPattern = /^\/\/[A-Za-z0-9._/-]*:[A-Za-z0-9._-]+$/;
/**
 * Resolves the workspace `gitHooks` bindings to labels through the index.
 *
 * Every bound hook target must be labeled: an unlisted target has no CLI
 * spelling for a script to invoke, so binding one is a graph error, not a
 * silently skipped hook.
 *
 * @category rendering
 * @since 0.1.0
 */
export const resolveHookLabels = (workspace, resolve) => {
    const bindings = {};
    if (workspace.gitHooks === undefined)
        return bindings;
    for (const hook of hookNames) {
        const target = workspace.gitHooks[hook];
        if (target === undefined)
            continue;
        const label = resolve.labelOf(target);
        if (label === undefined) {
            throw new GitHooksError("unlabeled_hook_target", `the ${hook} hook binds a target of rule ${Target.metadata(target).target} that no Package map lists; hooks need a label to invoke`);
        }
        bindings[hook] = label;
    }
    return bindings;
};
/** The first line every generated script carries after the shebang. */
const generatedHeader = "# Generated by smthrs from the WORKSPACE.ts gitHooks declaration. Do not edit.";
/** Renders one hook script for one bound label. */
const renderScript = (hookFile, label) => {
    if (!labelPattern.test(label)) {
        throw new GitHooksError("invalid_label", `${JSON.stringify(label)} is not a renderable target label`);
    }
    return [
        "#!/bin/sh",
        generatedHeader,
        `# ${hookFile} -> ${label}`,
        "if command -v smthrs >/dev/null 2>&1; then",
        `  exec smthrs '${label}'`,
        "fi",
        "if command -v smithers-build >/dev/null 2>&1; then",
        `  exec smithers-build '${label}'`,
        "fi",
        `echo "smthrs: CLI not found on PATH; skipping the ${hookFile} hook (fail-open)" >&2`,
        "exit 0",
        ""
    ].join("\n");
};
/**
 * Renders the deterministic hook script set for resolved bindings.
 *
 * The result maps git hook file names (`pre-commit`, ...) to script bytes,
 * in the fixed {@link hookNames} order.
 *
 * @category rendering
 * @since 0.1.0
 */
export const render = (bindings) => {
    const rendered = [];
    for (const hook of hookNames) {
        const label = bindings[hook];
        if (label === undefined)
            continue;
        rendered.push({ file: hookFiles[hook], content: renderScript(hookFiles[hook], label) });
    }
    return rendered;
};
