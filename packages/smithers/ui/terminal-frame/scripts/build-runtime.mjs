/**
 * Generates `src/runtime.generated.ts`: the frame runtime, with xterm.js and
 * its fit addon, that `TerminalFrame` writes into each frame and pins by hash.
 *
 * `node scripts/build-runtime.mjs` writes it; `--check` exits 1 when it is
 * stale. `test/runtime-generated.test.ts` runs the same comparison, so a
 * change to the frame's sources fails until this is run again.
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const target = "src/runtime.generated.ts";

const runtime = async () => {
  const result = await build({
    entryPoints: ["src/runtime.ts"],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    absWorkingDir: root,
    logLevel: "silent",
    define: { "process.env.NODE_ENV": "\"production\"" },
  });
  return result.outputFiles[0].text;
};

/** The generated module's path and its contents. */
export const generated = async () => ({
  [target]: "/* Generated by scripts/build-runtime.mjs from src/runtime.ts. Do not edit; run `node scripts/build-runtime.mjs`. */\n" +
    `export const terminalFrameRuntime: string = ${JSON.stringify(await runtime())};\n`,
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, contents] of Object.entries(await generated())) {
    const current = await readFile(join(root, path), "utf8").catch(() => undefined);
    if (current === contents) continue;
    if (process.argv.includes("--check")) {
      process.stderr.write(`Stale: ${path}. Run \`node scripts/build-runtime.mjs\` in packages/smithers/ui/terminal-frame.\n`);
      process.exit(1);
    }
    await writeFile(join(root, path), contents);
  }
}
