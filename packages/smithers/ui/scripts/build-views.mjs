/**
 * Generates the two scripts generated views run on, from their sources:
 *
 * - `src/presentation/bundle.generated.ts`: the presentation bundle a
 *   `PresentationRealm` loads (React, its static renderer and the subset);
 * - `src/generated-view/runtime.generated.ts`: the frame runtime
 *   `GeneratedView` writes into each frame and pins by hash.
 *
 * `node scripts/build-views.mjs` writes them; `--check` exits 1 when either is
 * stale. `tests/views-generated.test.ts` runs the check, so a change to a
 * subset component, the sanitizer or the bridge client fails until this is
 * run again.
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(join(root, "package.json"));
const legacyServer = join(dirname(require.resolve("react-dom/package.json")), "cjs/react-dom-server-legacy.browser.production.js");

const common = {
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  charset: "utf8",
  absWorkingDir: root,
  logLevel: "silent",
  define: { "process.env.NODE_ENV": "\"production\"" },
};

const presentation = async () => {
  const result = await build({
    ...common,
    entryPoints: ["src/presentation/entry.ts"],
    plugins: [{
      name: "realm",
      setup: (plugin) => {
        plugin.onResolve({ filter: /^react-dom\/server$/ }, () => ({ path: legacyServer }));
        plugin.onResolve({ filter: /^\.\.?\/styles$/ }, () => ({ path: "styles", namespace: "realm-stub" }));
        plugin.onLoad({ filter: /.*/, namespace: "realm-stub" }, () => ({
          contents: "export const useInjectUiCss = () => {};",
          loader: "js",
        }));
      },
    }],
  });
  return result.outputFiles[0].text;
};

const runtime = async () => {
  const result = await build({ ...common, entryPoints: ["src/generated-view/runtime.ts"] });
  return result.outputFiles[0].text;
};

const module = (comment, name, source) =>
  `/* Generated by scripts/build-views.mjs from ${comment}. Do not edit; run \`node scripts/build-views.mjs\`. */\n` +
  `export const ${name}: string = ${JSON.stringify(source)};\n`;

export const generated = async () => ({
  "src/presentation/bundle.generated.ts": module("src/presentation/entry.ts", "presentationBundle", await presentation()),
  "src/generated-view/runtime.generated.ts": module("src/generated-view/runtime.ts", "frameRuntime", await runtime()),
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await generated();
  const stale = [];
  for (const [path, contents] of Object.entries(files)) {
    const current = await readFile(join(root, path), "utf8").catch(() => undefined);
    if (current === contents) continue;
    if (process.argv.includes("--check")) stale.push(path);
    else await writeFile(join(root, path), contents);
  }
  if (stale.length > 0) {
    process.stderr.write(`Stale: ${stale.join(", ")}. Run \`node scripts/build-views.mjs\` in packages/smithers/ui.\n`);
    process.exit(1);
  }
}
