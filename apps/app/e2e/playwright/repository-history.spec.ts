import type { Locator, Page } from "@playwright/test"
import { expect, test } from "./browserTest"
import { identityRoute } from "./identity"
async function tabThrough(region: Locator, page: Page) {
 const controls=region.locator("a,button:not(:disabled),select")
 await controls.first().focus()
 for(let i=0;i<await controls.count();i++){await expect(controls.nth(i)).toBeFocused();await page.keyboard.press("Tab")}
}
const sha = "a".repeat(40)
const commit = { sha, short_sha: "aaaaaaa", title: "Serve real history", body: "Keep immutable identities.", author: "Ada", authored_at: "2026-10-18T10:00:00Z", committed_at: "2026-10-18T10:00:00Z", parents: ["b".repeat(40)] }
for (const width of [1440, 1280, 390]) for (const theme of ["light", "dark"] as const) {
 test(`history ${width} ${theme}`, async ({ page }, info) => {
  const shot=(name:string)=>process.env.SMITHERS_HISTORY_SHOTS ? `${process.env.SMITHERS_HISTORY_SHOTS}/${name}` : info.outputPath(name)
  await page.setViewportSize({width, height: width === 390 ? 844 : 900})
  await page.emulateMedia({colorScheme: theme})
  await page.route("**/api/bootstrap", route => route.fulfill({ json: { apiVersion: 1, host: "cloud", version: "test", buildSha: "test", capabilities: ["identity", "cloud"], authFlow: "redirect", sandbox: null } }))
  await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute(null))
  await page.route("**/api/public/repos", route => route.fulfill({json:{repos:[{name:"alpha/one"}]}}))
  await page.route("**/api/repos/alpha/one", route => route.fulfill({json:{default_bookmark:"main",is_public:true}}))
  await page.route("**/api/repos/alpha/one/bookmarks?*", route => route.fulfill({json:{items:[{name:"main",target_change_id:"change",target_commit_id:sha}],next_cursor:""}}))
  let releaseCommit!:()=>void, releaseBranches!:()=>void, releaseHistory!:()=>void
  const commitGate=new Promise<void>(r=>{releaseCommit=r}),branchGate=new Promise<void>(r=>{releaseBranches=r}),historyGate=new Promise<void>(r=>{releaseHistory=r})
  let commitMode: "ready"|"error"|"missing"="ready", branchMode: "ready"|"error"|"empty"="ready"
  await page.route(`**/api/repos/alpha/one/commits/${sha}`, async route=>{
   await commitGate
   return commitMode === "error" ? route.fulfill({status:503,json:{message:"Unavailable"}}) : commitMode === "missing" ? route.fulfill({status:404,json:{message:"Not found"}}) : route.fulfill({json:{...commit,files:[{path:"src/index.ts",status:"modified",additions:3,deletions:1}]}})
  })
  await page.route("**/api/repos/alpha/one/branches?*",async route=>{await branchGate;return branchMode==="error"?route.fulfill({status:503,json:{message:"Unavailable"}}):route.fulfill({json:{items:branchMode==="empty"?[]:[{name:"work/fix",head:sha,author:"Ada",updated:commit.committed_at,title:commit.title,is_default:false},{name:"main",head:sha,author:"Ada",updated:commit.committed_at,title:commit.title,is_default:true}]}})})
  let mode: "ready" | "error" | "empty" = "ready"
  await page.route("**/api/repos/alpha/one/commits?*", async route => {await historyGate; return mode === "error" ? route.fulfill({status:503,json:{message:"History unavailable"}}) : route.fulfill({json:{items:mode === "empty" ? [] : [commit], ...(new URL(route.request().url()).searchParams.has("cursor") ? {} : {next_cursor:"next"})}})})
  await page.goto("/alpha/one/commits/main")
  const view=page.getByRole("region",{name:"Commit history"})
  await expect(view.getByRole("status")).toBeVisible()
  await page.screenshot({path:shot(`history-commits-loading.${width}.${theme}.png`)})
  releaseHistory()
  await expect(view.getByRole("link",{name:commit.title})).toBeVisible()
  await expect(page.locator(".repo-frame")).toBeVisible()
  await expect(view).toContainText("Ada")
  await expect(view).not.toContainText("Verified")
  await page.screenshot({path:shot(`history-commits-main.${width}.${theme}.png`)})
  await tabThrough(view,page)
  const older=page.waitForRequest(r=>r.url().includes("cursor=next"))
  await view.getByRole("link",{name:"Older",exact:true}).press("Enter"); await older
  await expect(view.getByRole("link",{name:"Newer",exact:true})).toBeEnabled()
  await expect(page).toHaveURL(/cursor=next/)
  await page.reload(); await expect(view.getByRole("link",{name:commit.title})).toBeVisible()
  await expect(page).toHaveURL(/cursor=next/)
  await view.getByRole("link",{name:"Newer",exact:true}).press("Enter")
  await expect(page).toHaveURL(/\/commits\/main$/)
  await expect(view.getByRole("link",{name:commit.title})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const documentId=await page.evaluate(()=>{(window as unknown as {historyProof:string}).historyProof="same-document";return "same-document"})
  await view.getByRole("link",{name:commit.title}).press("Enter")
  const detail=page.getByRole("region",{name:"Commit",exact:true})
  await expect(detail.getByRole("status")).toBeVisible()
  await page.screenshot({path:shot(`history-commit-loading.${width}.${theme}.png`)})
  releaseCommit()
  await expect(detail.getByRole("heading",{name:commit.title})).toBeVisible()
  await expect(detail).toContainText(commit.body)
  await expect(detail.getByRole("link",{name:"bbbbbbb",exact:true})).toHaveAttribute("href","/alpha/one/commit/"+commit.parents[0])
  await expect(detail).toContainText("src/index.ts")
  expect(await page.evaluate(()=>(window as unknown as {historyProof:string}).historyProof)).toBe(documentId)
  await page.screenshot({path:shot(`history-commit-human.${width}.${theme}.png`)})
  await tabThrough(detail,page)
  await page.reload();await expect(detail.getByRole("heading",{name:commit.title})).toBeVisible()
  commitMode="error";await page.reload();await expect(detail.getByRole("alert")).toBeVisible()
  await page.screenshot({path:shot(`history-commit-error.${width}.${theme}.png`)})
  commitMode="ready";await detail.getByRole("button",{name:"Retry",exact:true}).press("Enter");await expect(detail.getByRole("heading",{name:commit.title})).toBeVisible()
  commitMode="missing";await page.reload();await expect(detail).toContainText("Commit not found.")
  await page.screenshot({path:shot(`history-commit-empty.${width}.${theme}.png`)})
  await page.goto("/alpha/one/branches")
  const branches=page.getByRole("region",{name:"Branches",exact:true})
  await expect(branches.getByRole("status")).toBeVisible()
  await page.screenshot({path:shot(`history-branches-loading.${width}.${theme}.png`)})
  releaseBranches()
  await expect(branches.locator("a[data-branch]").first()).toHaveText("main")
  await expect(branches.getByRole("link",{name:"work/fix",exact:true})).toHaveAttribute("href","/alpha/one/tree/work/fix")
  await expect(branches).not.toContainText("2026-10-18")
  await expect(branches.getByRole("button",{name:"New branch"})).toHaveCount(0)
  await page.screenshot({path:shot(`history-branches.${width}.${theme}.png`)})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await tabThrough(branches,page)
  branchMode="error";await page.reload();await expect(branches.getByRole("alert")).toBeVisible()
  await page.screenshot({path:shot(`history-branches-error.${width}.${theme}.png`)})
  branchMode="empty";await branches.getByRole("button",{name:"Retry",exact:true}).press("Enter");await expect(branches).toContainText("No branches found.")
  await page.screenshot({path:shot(`history-branches-empty.${width}.${theme}.png`)})
  await page.goto("/alpha/one/commits/main")
  mode="error";await page.reload();await expect(view.getByRole("alert")).toBeVisible()
  await page.screenshot({path:shot(`history-commits-error.${width}.${theme}.png`)})
  mode="empty";await view.getByRole("button",{name:"Retry",exact:true}).press("Enter");await expect(view).toContainText("No commits found.")
  await page.screenshot({path:shot(`history-commits-empty.${width}.${theme}.png`)})
 })
}
