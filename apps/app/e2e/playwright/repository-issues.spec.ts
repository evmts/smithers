    await page.route(/\/api\/repos\/maya\/tinyhttp\/issues(?:\?.*)?$/, route => route.fulfill({ json: [{ number: 9, title: "Native tracker row", body: "Native body", state: "open", author: { login: "maya" }, labels: [], assignees: [], comment_count: 0 }] }))
