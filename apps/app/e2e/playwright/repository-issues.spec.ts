for (const repo of ["effeck/effeck", "smithers-canary/smithers"]) test(`signed-out native repository ${repo} uses its own tracker and truthful empty pulls`, async ({ page }) => {
  await signedOutVisitor(page)
  const githubReads: string[] = []
  page.on("request", request => { if (request.url().includes(`github-repos/${repo}/`) || request.url().includes(`repos/${repo}/github/metadata`)) githubReads.push(request.url()) })
  await page.route("**/api/public/repos", route => route.fulfill({ json: { repos: [{ name: repo }] } }))
  await page.route(`**/api/repos/${repo}`, route => route.fulfill({ json: { full_name: repo, is_public: true, default_bookmark: "main", issue_tracker: "smithers-cloud", github_source: {owner: "smithersai", repo: "smithers"} } }))
  await page.route(new RegExp(`/api/repos/${repo}/issues(?:\\?.*)?$`), route => route.fulfill({ json: [{ number: 3, title: "Native repository issue", state: "open", author: { login: "will" }, labels: [], comment_count: 0 }] }))
  await page.route(`**/api/repos/${repo}/issues/3`, route => route.fulfill({ json: { number: 3, title: "Native repository issue", body: "Native conversation", state: "open", author: { login: "will" }, labels: [] } }))
  await page.route(`**/api/repos/${repo}/issues/3/comments`, route => route.fulfill({ json: [] }))
  await page.route(`**/api/repos/${repo}/issue-views`, route => route.fulfill({ json: [] }))
  const landings = repo === "effeck/effeck" ? [] : [{number: 12, title: "Native repository landing", state: "open", author: {login: "will"}, change_ids: [], target_bookmark: "main"}]
  await page.route(`**/api/repos/${repo}/landings?*`, route => route.fulfill({json: landings}))
  await page.goto(`/${repo}/issues`)
  await expect(page.getByRole("main").getByRole("link", { name: "Native repository issue", exact: true })).toBeVisible()
  await page.goto(`/${repo}/issues/3`)
  await expect(page.getByRole("main").getByRole("heading", { name: "Native repository issue #3" })).toBeVisible()
  await page.goto(`/${repo}/pulls`)
  if (landings.length === 0) await expect(page.getByRole("main").getByRole("heading", {name: "No pull requests.", exact: true})).toBeVisible()
  else await expect(page.getByRole("main").getByRole("link", {name: "Native repository landing", exact: true})).toHaveAttribute("href", `/${repo}/pull/12`)
  await expect(page.getByRole("main").getByRole("button", { name: "Retry", exact: true })).toHaveCount(0)
  expect(githubReads).toEqual([])
})

test("signed-out GitHub-backed repository reads source rows and shows sync age", async ({ page }) => {
  await signedOutVisitor(page)
  const repo = "smithers-canary/smithers"
  const headers = { "X-Metadata-Stale": "true", "X-Metadata-Synced-At": "2026-09-16T12:00:00Z" }
  const issue = { number: 7, title: "Mirrored repository issue", body: "Mirror conversation", state: "open", user: { login: "will" }, labels: [], comments: 0 }
  const pull = { number: 34, title: "Mirrored repository pull", state: "open", user: { login: "will" }, labels: [] }
  const reads: string[] = []
  page.on("request", request => { if (/github-repos|github\/metadata/.test(request.url())) reads.push(request.url()) })
  await page.route("**/api/public/repos", route => route.fulfill({ json: { repos: [{ name: repo }] } }))
  await page.route(`**/api/repos/${repo}`, route => route.fulfill({ json: { full_name: repo, is_public: true, default_bookmark: "main", issue_tracker: "github", github_source: { owner: "smithersai", repo: "smithers" } } }))
  await page.route(new RegExp(`/api/repos/${repo}/issues(?:\\?.*)?$`), route => route.fulfill({ json: [] }))
  await page.route(`**/api/repos/${repo}/issue-views`, route => route.fulfill({ json: [] }))
  await page.route(`**/api/user/github-repos/${repo}/issues?*`, route => route.fulfill({ status: 401, json: {message: "authentication required"} }))
  await page.route(`**/api/user/github-repos/${repo}/issues/7/comments*`, route => route.fulfill({ status: 401, json: {message: "authentication required"} }))
  // Since #4320 the proxy is addressed by the declared GitHub source, as the pulls read below already is; signed out it refuses.
  await page.route("**/api/user/github-repos/smithersai/smithers/issues?*", route => route.fulfill({ status: 401, json: {message: "authentication required"} }))
  await page.route("**/api/user/github-repos/smithersai/smithers/issues/7/comments*", route => route.fulfill({ status: 401, json: {message: "authentication required"} }))
  await page.route(`**/api/repos/${repo}/github/metadata/issues?*`, route => route.fulfill({ json: [issue], headers }))
  await page.route(`**/api/repos/${repo}/github/metadata/issues/7/comments*`, route => route.fulfill({ json: [] }))
  await page.route("**/api/user/github-repos/smithersai/smithers/pulls?*", route => route.fulfill({ status: 401, json: {message: "authentication required"} }))
  await page.route(`**/api/repos/${repo}/github/metadata/pulls?*`, route => route.fulfill({ json: [pull], headers }))
  await page.goto(`/${repo}/issues`)
  const main = page.getByRole("main")
  await expect(main.getByRole("link", { name: issue.title, exact: true })).toBeVisible()
  await expect(main.getByRole("status")).toContainText("Stale · synced")
  await page.goto(`/${repo}/issues/7`)
  await expect(main.getByRole("heading", { name: `${issue.title} #7`, exact: true })).toBeVisible()
  await expect(main.getByRole("status")).toContainText("Stale · synced")
  await page.goto(`/${repo}/pulls`)
  await expect(main.getByRole("link", { name: pull.title, exact: true })).toBeVisible()
  await expect(main.getByRole("status")).toContainText("Stale · synced")
  expect(reads.some(url => url.includes(`/api/repos/${repo}/github/metadata/issues`))).toBe(true)
  expect(reads.some(url => url.includes(`/api/repos/${repo}/github/metadata/pulls`))).toBe(true)
})

test("signed-in New issue creates in the native repository tracker", async ({ page }) => {
  await signedOutVisitor(page)
  await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute())
  const repo = "effeck/effeck"
  const writes: string[] = []
  const issue = { number: 4, title: "Native creation", body: "", state: "open", author: {login: "will"}, labels: [], comment_count: 0 }
  await page.route("**/api/public/repos", route => route.fulfill({json: {repos: [{name: repo}]}}))
  await page.route(`**/api/repos/${repo}`, route => route.fulfill({json: {full_name: repo, is_public: true, default_bookmark: "main", issue_tracker: "smithers-cloud", github_source: {owner: "smithersai", repo: "smithers"}}}))
  await page.route(`**/api/repos/${repo}/issue-views`, route => route.fulfill({json: []}))
  await page.route(new RegExp(`/api/repos/${repo}/issues(?:\\?.*)?$`), route => {
    if (route.request().method() === "POST") {
      writes.push(new URL(route.request().url()).pathname)
      return route.fulfill({json: issue})
    }
    return route.fulfill({json: []})
  })
  await page.route(`**/api/repos/${repo}/issues/4`, route => route.fulfill({json: issue}))
  await page.route(`**/api/repos/${repo}/issues/4/comments`, route => route.fulfill({json: []}))
  await page.route(`**/api/repos/${repo}/github/issues`, route => {
    writes.push(new URL(route.request().url()).pathname)
    return route.fulfill({status: 400, json: {message: "Wrong tracker"}})
  })
  await page.goto(`/${repo}/issues`)
  await page.getByRole("main").getByRole("button", {name: "New issue", exact: true}).click()
  const ask = page.getByRole("complementary", {name: "Ask", exact: true})
  await ask.getByRole("textbox", {name: /title/i}).fill(issue.title)
  await ask.getByRole("button", {name: "Submit", exact: true}).click()
  await expect.poll(() => writes).toEqual([`/api/repos/${repo}/issues`])
  await expect(ask.getByRole("heading", {name: "Native creation #4", exact: true})).toBeVisible()
})

test("a full GitHub page that links a next page draws its issue counts as floors", async ({ page }) => {
  await signedOutVisitor(page)
  // GitHub's default page: 30 rows and a next link. Live it read "Open 29 Closed 1" as the repository's totals (PM d-i55b5a).
  const issues = Array.from({ length: 30 }, (_, i) => ({ number: 30 - i, title: `Paged issue ${30 - i}`, state: i < 29 ? "open" : "closed", user: { login: "maya" }, labels: [], comments: 0, created_at: "2026-10-17T12:00:00Z" }))
  await page.route("**/api/public/repos", route => route.fulfill({ json: { repos: [{ name: "maya/tinyhttp" }] } }))
  await page.route("**/api/repos/maya/tinyhttp", route => route.fulfill({ json: { full_name: "maya/tinyhttp", is_public: true, default_bookmark: "main", github_source: { owner: "maya", repo: "tinyhttp" } } }))
  await page.route(/\/api\/repos\/maya\/tinyhttp\/issues(?:\?.*)?$/, route => route.fulfill({ json: [] }))
  await page.route("**/api/user/github-repos/maya/tinyhttp/issues?*", route => route.fulfill({ json: issues, headers: { link: '<https://api.github.com/repositories/1/issues?state=all&page=2>; rel="next"' } }))
  await page.goto("/maya/tinyhttp/issues")
  const state = page.getByRole("main").getByRole("navigation", { name: "Issue state", exact: true })
  await expect(state.getByRole("link", { name: /Open 29\+$/ })).toBeVisible()
  await expect(state.getByRole("link", { name: /Closed 1\+$/ })).toBeVisible()
  await expect(page.getByRole("navigation", { name: "Repository", exact: true }).getByRole("link", { name: "Issues 29+", exact: true })).toBeVisible()
})
