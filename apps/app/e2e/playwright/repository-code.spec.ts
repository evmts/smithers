import { expect, test } from "./browserTest"
import { identityRoute } from "./identity"

for (const width of [1280, 390]) for (const theme of ["light", "dark"] as const) {
  test(`tree and blob views ${width} ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ colorScheme: theme })
    await page.route("**/api/bootstrap", route => route.fulfill({ json: { apiVersion: 1, host: "cloud", version: "test", buildSha: "test", capabilities: ["identity", "cloud"], authFlow: "native-handoff", sandbox: null } }))
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute(null))
    await page.route("**/api/public/repos", route => route.fulfill({ json: { repos: [{ name: "alpha/one" }] } }))
    await page.route("**/api/repos/alpha/one", route => route.fulfill({ json: { default_bookmark: "main", is_public: true } }))
    await page.route("**/api/repos/alpha/one/bookmarks?*", route => route.fulfill({ json: { items: [{ name: "main", target_change_id: "change", target_commit_id: "a".repeat(40) }], next_cursor: "" } }))
    await page.route(/\/api\/repos\/alpha\/one\/contents(?:\/[^?]*)?(?:\?.*)?$/, route => {
      const path = new URL(route.request().url()).pathname
      if (path.endsWith("/missing.ts")) return route.fulfill({ status: 404, json: { message: "Path not found" } })
      if (path.endsWith("/large.ts")) return route.fulfill({ json: { type: "file", content: "// long file\n".repeat(9000), encoding: "utf-8" } })
      return route.fulfill({ json: path.endsWith("/index.ts") ? { type: "file", content: "export const answer = 42\n// final line\n", encoding: "utf-8" } : [{ name: "index.ts", path: "src/index.ts", type: "file" }] })
    })
    await page.goto("/alpha/one/issues")
    await expect(page.getByRole("button", { name: "Chat", exact: true })).toBeVisible()
    await page.keyboard.press("Control+k")
    const composer = page.getByTestId("composer-input")
    await composer.fill(`/theme ${theme}`)
    await composer.press("Enter")
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme)
    await page.goto("/alpha/one/tree/main/src")
    await expect(page.locator(".session-navigation")).toBeHidden()
    const bounds = await page.locator(".repo-frame").boundingBox()
    expect(bounds?.width).toBe(width)
    expect(bounds?.y).toBe(0)
    const folder = page.getByRole("region", { name: "Folder view" })
    await expect(page.getByRole("navigation", { name: "Repository", exact: true })).toBeVisible()
    await expect(folder.getByRole("table", { name: "Files in src" })).toBeVisible()
    const file = folder.getByRole("link", { name: "index.ts", exact: true })
    await page.screenshot({ path: `/tmp/sp1b-tree-${width}-${theme}.png` })
    await expect(file).toHaveAttribute("href", "/alpha/one/blob/main/src/index.ts")
    await file.focus(); await expect(file).toBeFocused(); await page.keyboard.press("Enter")
    const view = page.getByRole("region", { name: "File view" })
    await expect(view.getByRole("region", { name: "Source of src/index.ts" })).toContainText("// final line")
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme)
    await page.screenshot({ path: `/tmp/sp1b-blob-${width}-${theme}.png` })
    await expect(view.getByText("Truncated", { exact: true })).toHaveCount(0)
    await expect(page.locator(".repo-ui-btn-primary:visible")).toHaveCount(1)
    await expect(view.getByRole("button", { name: "Blame", exact: true })).toHaveCount(0)
    for (const name of ["Copy permalink", "Raw", "Copy file contents"]) {
      const control = view.getByRole("button", { name, exact: true }); await control.focus(); await expect(control).toBeFocused()
    }
    const controls = view.locator("a, button, select")
    await controls.first().focus()
    for (let i = 0; i < await controls.count(); i++) {
      await expect(controls.nth(i)).toBeFocused()
      await page.keyboard.press("Tab")
    }
    const line = view.getByRole("link", { name: "Select line 2", exact: true })
    await line.focus(); await page.keyboard.press("Enter")
    await expect(page).toHaveURL(/\?L=2$/)
    await view.getByRole("link", { name: "Select line 1", exact: true }).press("Shift+Enter")
    await expect(page).toHaveURL(/\?L=1-2$/)
    await line.press("Shift+Enter")
    await expect(page).toHaveURL(/\?L=2$/)
    await page.reload()
    await expect(view.getByRole("button", { name: "Ask about lines", exact: true })).toBeVisible()
    await expect(view.getByText("Make TODO", { exact: true })).toHaveCount(0)
    await view.getByRole("button", { name: "Raw", exact: true }).click()
    await expect(view.getByLabel("Raw src/index.ts", { exact: true })).toHaveText("export const answer = 42\n// final line\n")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.goto("/alpha/one/blob/main/src/missing.ts")
    await expect(page.getByRole("region", { name: "File view" }).getByRole("alert")).toContainText("Path not found")
    await expect(page.getByText("This file is empty.", { exact: true })).toHaveCount(0)
    await page.goto("/alpha/one/blob/main/src/large.ts")
    await expect(page.getByRole("region", { name: "File view" }).getByRole("status")).toHaveText("Truncated")
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute("reader"))
    await page.goto("/alpha/one/blob/main/src/index.ts?L=2")
    await page.getByRole("button", { name: "Ask about lines", exact: true }).click()
    await expect(page.getByRole("complementary", { name: "Ask", exact: true })).toBeVisible()
    await expect(page.getByTestId("composer-input")).toHaveValue("Explain lines 2-2 of src/index.ts at main")
  })
}
