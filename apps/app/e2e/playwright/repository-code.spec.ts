import { expect, test } from "./browserTest"
import { APPLICATION_SIGN_IN_PATH } from "@smthrs/rpc/ApplicationAuth"
import { identityRoute } from "./identity"

for (const width of [1440, 1280, 390]) for (const theme of ["light", "dark"] as const) {
  test(`tree and blob views ${width} ${theme}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 844 })
    await page.emulateMedia({ colorScheme: theme })
    await page.route("**/api/bootstrap", route => route.fulfill({ json: { apiVersion: 1, host: "cloud", version: "test", buildSha: "test", capabilities: ["identity", "cloud"], authFlow: "redirect", sandbox: null } }))
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute(null))
    await page.route("**/api/public/repos", route => route.fulfill({ json: { repos: [{ name: "alpha/one" }] } }))
    await page.route("**/api/repos/alpha/one", route => route.fulfill({ json: { default_bookmark: "main", is_public: true } }))
    await page.route("**/api/repos/alpha/one/bookmarks?*", route => route.fulfill({ json: { items: [{ name: "main", target_change_id: "change", target_commit_id: "a".repeat(40) }], next_cursor: "" } }))
    await page.route(/\/api\/repos\/alpha\/one\/contents(?:\/[^?]*)?(?:\?.*)?$/, route => {
      const path = new URL(route.request().url()).pathname
      if (path.endsWith("/missing.ts")) return route.fulfill({ status: 404, json: { message: "Path not found" } })
      if (path.endsWith("/sized.ts")) return route.fulfill({ json: { type: "file", content: "x".repeat(20000), size: 20000, encoding: "utf-8", commit_sha: "b".repeat(40), raw_url: "/api/repos/alpha/one/contents/src/sized.ts?raw=1" } })
      if (path.endsWith("/large.ts")) return route.fulfill({ json: { type: "file", content: "// long file\n".repeat(9000) + "// FINAL LINE", size: 108013, encoding: "utf-8", commit_sha: "b".repeat(40), raw_url: "/api/repos/alpha/one/contents/src/large.ts?raw=1" } })
      if (path.endsWith("/huge.ts")) return route.fulfill({ json: { type: "file", content: "", size: 524289, too_large: true, commit_sha: "b".repeat(40), raw_url: "/api/repos/alpha/one/contents/src/huge.ts?raw=1&ref=" + "b".repeat(40) } })
      return route.fulfill({ headers: { "X-Contents-Commit": "b".repeat(40) }, json: path.endsWith("/index.ts") ? { type: "file", content: "export const answer = 42\n// final line\n", size: 40, encoding: "utf-8", commit_sha: "b".repeat(40), raw_url: "/api/repos/alpha/one/contents/src/index.ts?raw=1" } : [{ name: "index.ts", path: "src/index.ts", type: "file" }] })
    })
    // Set the persisted theme as a signed-in person, then read the public repository signed out.
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute("reader"))
    await page.goto("/")
    await expect(page.getByRole("button", { name: "Chat", exact: true })).toBeVisible()
    await page.keyboard.press("Control+k")
    const composer = page.getByTestId("composer-input")
    await composer.fill(`/theme ${theme}`)
    await composer.press("Enter")
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme)
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute(null))
    await page.goto("/alpha/one/tree/main/src")
    await expect(page.locator(".session-navigation")).toBeHidden()
    const bounds = await page.locator(".repo-frame").boundingBox()
    expect(bounds?.width).toBe(width)
    expect(bounds?.y).toBe(0)
    const folder = page.getByRole("region", { name: "Folder view" })
    await expect(page.getByRole("navigation", { name: "Repository", exact: true })).toBeVisible()
    await expect(folder.getByRole("table", { name: "Files in src" })).toBeVisible()
    const file = folder.getByRole("link", { name: "index.ts", exact: true })
    await page.screenshot({ path: testInfo.outputPath(`sp1b-tree-${width}-${theme}.png`) })
    await expect(file).toHaveAttribute("href", "/alpha/one/blob/main/src/index.ts")
    await file.focus(); await expect(file).toBeFocused(); await page.keyboard.press("Enter")
    const view = page.getByRole("region", { name: "File view" })
    await expect(view.getByRole("region", { name: "Source of src/index.ts" })).toContainText("// final line")
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme)
    await page.screenshot({ path: testInfo.outputPath(`sp1b-blob-${width}-${theme}.png`) })
    await expect(view.getByText("Truncated", { exact: true })).toHaveCount(0)
    await expect(page.locator(".repo-ui-btn-primary:visible")).toHaveCount(1)
    await expect(view.getByRole("button", { name: "Blame", exact: true })).toHaveCount(0)
    for (const name of ["Copy permalink", "Raw", "Copy file contents"]) {
      const control = view.getByRole("button", { name, exact: true }); await control.focus(); await expect(control).toBeFocused()
    }
    // The branch button's closed list is not in the ring; its summary is.
    const controls = view.locator("a:visible, button:visible, summary:visible")
    await controls.first().focus()
    for (let i = 0; i < await controls.count(); i++) {
      await expect(controls.nth(i)).toBeFocused()
      await page.keyboard.press("Tab")
    }
    const line = view.getByRole("link", { name: "Select line 2", exact: true })
    await line.focus(); await page.keyboard.press("Enter")
    await expect(page).toHaveURL(/\?L=2$/)
    await view.getByRole("link", { name: "Select line 1", exact: true }).press("Shift+Enter")
    await expect(page).toHaveURL(/\?L=1-2$/)
    await line.press("Shift+Enter")
    await expect(page).toHaveURL(/\?L=2$/)
    await page.reload()
    await expect(view.getByRole("button", { name: "Ask about lines", exact: true })).toBeVisible()
    await expect(view.getByText("Make TODO", { exact: true })).toHaveCount(0)
    await page.route("**/api/auth/github**", route => route.fulfill({ body: "Sign-in handoff" }))
    const signIn = page.waitForRequest(request => new URL(request.url()).pathname === APPLICATION_SIGN_IN_PATH)
    await view.getByRole("button", { name: "Ask about lines", exact: true }).click()
    await signIn
    await page.goto("/alpha/one/blob/main/src/index.ts?L=2")
    await view.getByRole("button", { name: "Raw", exact: true }).click()
    await expect(view.getByLabel("Raw src/index.ts", { exact: true })).toHaveText("export const answer = 42\n// final line\n")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.goto("/alpha/one/blob/main/src/missing.ts")
    await expect(page.getByRole("region", { name: "File view" }).getByRole("alert")).toContainText("Could not read file.")
    await expect(page.getByText("This file is empty.", { exact: true })).toHaveCount(0)
    await page.goto("/alpha/one/blob/main/src/large.ts")
    await expect(view.getByRole("link", { name: "Select line 9001", exact: true })).toBeVisible()
    await expect(view.locator('[data-line="9001"] code')).toHaveText("// FINAL LINE")
    await expect(view.getByText("Truncated", { exact: true })).toHaveCount(0)
    await page.goto("/alpha/one/blob/main/src/huge.ts")
    await expect(view.getByText("524,289 B", { exact: true })).toBeVisible()
    const rawLink = view.getByRole("link", { name: "Raw", exact: true })
    await expect(rawLink).toHaveAttribute("href", "/api/repos/alpha/one/contents/src/huge.ts?raw=1&ref=" + "b".repeat(40))
    await rawLink.focus(); await expect(rawLink).toBeFocused()
    await expect(view.getByRole("region", { name: "Source of src/huge.ts" })).toHaveCount(0)
    await expect(view.getByRole("button", { name: "Copy file contents" })).toHaveCount(0)
    await page.goto("/alpha/one/blob/main/src/sized.ts")
    await expect(page.getByText("1 lines · 20,000 B", { exact: true })).toBeVisible()
    await page.route("**/api/repos/alpha/one", route => route.fulfill({ status: 503, json: { message: "Mirror unavailable" } }))
    await page.goto("/alpha/one/blob/main/src/index.ts")
    await expect(page.getByRole("region", { name: "File view" }).getByRole("alert")).toContainText("Repository unavailable (HTTP 503).")
    await expect(page.getByRole("region", { name: "File view" }).getByRole("status")).toHaveCount(0)
    await page.route("**/api/repos/alpha/one", route => route.fulfill({ json: { default_bookmark: "main", is_public: true } }))
    await page.route("**/api/repos/alpha/one/bookmarks?*", route => route.fulfill({ status: 401, json: { message: "Sign in" } }))
    await page.goto("/alpha/one/blob/main/src/index.ts?L=2")
    await page.context().grantPermissions(["clipboard-read", "clipboard-write"])
    await page.getByRole("button", { name: "Copy permalink", exact: true }).click()
    await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain(`/blob/${"b".repeat(40)}/src/index.ts?L=2`)
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute("reader"))
    await page.goto("/alpha/one/blob/main/src/index.ts?L=2")
    await expect(page.getByRole("region", { name: "File view" })).toBeVisible()
    await expect(page.getByRole("button", { name: "Ask", exact: true })).toBeVisible()
    // The document-capture shortcut must open the framed Ask, even below 1440.
    await page.keyboard.press("Control+k")
    await expect(page.getByRole("complementary", { name: "Ask", exact: true })).toBeVisible()
    await expect(page.getByTestId("composer-input")).toBeVisible()
    await page.getByRole("button", { name: "Close Ask", exact: true }).click()
    await expect(page.getByRole("complementary", { name: "Ask", exact: true })).toBeHidden()
    await page.getByRole("button", { name: "Ask about lines", exact: true }).click()
    await expect(page.getByRole("complementary", { name: "Ask", exact: true })).toBeVisible()
    await expect(page.getByTestId("composer-input")).toBeVisible()
    await expect(page.getByTestId("composer-input")).toHaveValue("Explain lines 2-2 of src/index.ts at main")
    await page.route(url => url.pathname === "/api/user" || url.pathname === "/api/auth/session", identityRoute(null))
    await page.route("**/api/bootstrap", route => route.fulfill({ json: { apiVersion: 1, host: "cloud", version: "test", buildSha: "test", capabilities: ["identity", "cloud"], authFlow: "redirect", sandbox: null } }))
    await page.goto("/alpha/one/blob/main/src/index.ts")
    await expect(page.getByRole("region", { name: "File view" })).toBeVisible()
    await page.route("**/api/auth/github**", route => route.fulfill({ body: "Sign-in handoff" }))
    const shortcutSignIn = page.waitForRequest(request => new URL(request.url()).pathname === APPLICATION_SIGN_IN_PATH)
    await page.keyboard.press("Control+k")
    await shortcutSignIn
    await page.waitForURL(url => url.pathname === APPLICATION_SIGN_IN_PATH)
  })
}
