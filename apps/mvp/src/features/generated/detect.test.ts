// Whether a repository file is generated (src/features/generated/detect.ts): the manifest first, then a header marker.
import { Option } from "effect"
import { describe, expect, test } from "vitest"
import { MAX_MANIFEST_BYTES } from "./contract"
import { generatedOf, hasMarker, nearestManifest, parseManifest } from "./detect"

const manifest = (outputs: unknown) => JSON.stringify({ outputs })

describe("the manifest", () => {
  test("reads `.smithers/generated.json`: each output's flow, inputs, cache key and run", () => {
    expect(parseManifest(manifest({ "dist/a.js": { flow: "build/js", inputs: ["src/a.ts"], cacheKey: "k1", run: "r1" } })))
      .toEqual(Option.some({ outputs: { "dist/a.js": { flow: "build/js", inputs: ["src/a.ts"], cacheKey: "k1", run: "r1" } } }))
    expect(parseManifest(manifest({ "docs/x.md": { flow: "docs" } }))).toEqual(
      Option.some({ outputs: { "docs/x.md": { flow: "docs" } } }),
    )
  })

  test("reads it as docs/generate writes it: its version, the flow's source, hashed inputs and the toolchain left out", () => {
    const written = JSON.stringify({
      version: 1,
      outputs: {
        "out/CONTRIBUTING.md": {
          flow: "docs/generate",
          source: ".smithers/flows/docs/flow.ts",
          inputs: [{ path: "project.ts", sha256: "6bd0" }, "render.ts"],
          toolchain: { bun: "1.4.1" },
          cacheKey: "7211",
          sha256: "cdca",
        },
      },
    })
    expect(parseManifest(written)).toEqual(Option.some({
      version: 1,
      outputs: {
        "out/CONTRIBUTING.md": {
          flow: "docs/generate",
          source: ".smithers/flows/docs/flow.ts",
          inputs: [{ path: "project.ts", sha256: "6bd0" }, "render.ts"],
          cacheKey: "7211",
          sha256: "cdca",
        },
      },
    }))
    expect(parseManifest(JSON.stringify({ version: 2, outputs: {} }))).toEqual(Option.none())
  })

  test("a manifest that is missing, too large, not JSON or not the shape marks nothing", () => {
    expect(parseManifest(undefined)).toEqual(Option.none())
    expect(parseManifest("{")).toEqual(Option.none())
    expect(parseManifest(JSON.stringify({ files: {} }))).toEqual(Option.none())
    expect(parseManifest(manifest({ "a": { flow: "Not A Tag" } }))).toEqual(Option.none())
    expect(parseManifest(manifest({ "a": { flow: "ok", inputs: [""] } }))).toEqual(Option.none())
    expect(parseManifest(" ".repeat(MAX_MANIFEST_BYTES) + manifest({}))).toEqual(Option.none())
  })
})

describe("the nearest manifest", () => {
  const paths = new Set([".smithers/generated.json", "docs/gen/.smithers/generated.json", "docs/gen/out/a.md"])

  test("its own folder's, else each folder above it, up to the root's", () => {
    expect(nearestManifest(paths, "docs/gen/out/a.md")).toBe("docs/gen/.smithers/generated.json")
    expect(nearestManifest(paths, "docs/other.md")).toBe(".smithers/generated.json")
    expect(nearestManifest(paths, "README.md")).toBe(".smithers/generated.json")
    expect(nearestManifest(new Set(["docs/gen/.smithers/generated.json"]), "src/a.ts")).toBeUndefined()
  })
})

describe("header markers", () => {
  test("`@generated` and Go's `Code generated … DO NOT EDIT`, in any comment style, in the first lines", () => {
    expect(hasMarker("// @generated by protoc\nexport {}")).toBe(true)
    expect(hasMarker("# Code generated by sqlc. DO NOT EDIT.\nx = 1")).toBe(true)
    expect(hasMarker("/*\n * code generated by tool; do not edit\n */")).toBe(true)
    expect(hasMarker("<!-- @generated -->\n<html>")).toBe(true)
  })

  test("a marker past the first five lines, or words that only look alike, don't count", () => {
    expect(hasMarker("1\n2\n3\n4\n5\n// @generated")).toBe(false)
    expect(hasMarker("// @generatedBy is a field\n")).toBe(false)
    expect(hasMarker("// Code generated by hand, edit freely")).toBe(false)
    expect(hasMarker("")).toBe(false)
  })
})

describe("generatedOf", () => {
  const listed = parseManifest(manifest({ "docs/api.md": { flow: "docs/build", inputs: ["src/api.ts"] } }))

  test("the manifest wins and names the flow; a marker alone names none; anything else is a person's", () => {
    expect(generatedOf("docs/api.md", "// @generated", listed)).toEqual({
      by: "manifest",
      output: { flow: "docs/build", inputs: ["src/api.ts"] },
    })
    expect(generatedOf("gen/x.go", "// Code generated by x. DO NOT EDIT.", listed)).toEqual({ by: "marker" })
    expect(generatedOf("src/api.ts", "export {}", listed)).toBeUndefined()
    expect(generatedOf("src/api.ts", undefined, Option.none())).toBeUndefined()
    // A path no output names, though an object inherits it, is no output.
    expect(generatedOf("constructor", undefined, listed)).toBeUndefined()
  })
})
