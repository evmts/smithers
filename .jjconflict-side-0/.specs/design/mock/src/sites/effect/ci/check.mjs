import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../../../../..');
const require = createRequire(join(root, 'apps/app/package.json'));
const { build } = require('esbuild');
const scratch = mkdtempSync(join(tmpdir(), 'effect-ci-check-'));
const storage = new Map();
globalThis.window = { location: { hash: '' }, addEventListener() {}, dispatchEvent() {} };
globalThis.sessionStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
try {
  await build({ entryPoints: [join(here, 'routes.tsx')], bundle: true, write: false, platform: 'browser', format: 'esm', jsx: 'automatic', nodePaths: [join(root, 'apps/app/node_modules'), join(root, 'node_modules')], alias: { '@smthrs/ui': join(root, 'packages/smithers/ui/src/index.ts') }, loader: { '.css': 'text' }, logLevel: 'silent' });
  const out = join(scratch, 'model.cjs');
  await build({ stdin: { contents: `export * as ci from ${JSON.stringify(join(here, 'model.ts'))}; export * as fixtures from ${JSON.stringify(join(root, '.specs/design/mock/src/sites/repo/fixtures/index.ts'))}; export * as commands from ${JSON.stringify(join(here, 'commands.ts'))}; export * as slash from ${JSON.stringify(join(root, '.specs/design/mock/src/sites/repo/frame/slash.ts'))};`, resolveDir: here }, outfile: out, platform: 'node', format: 'cjs', bundle: true, nodePaths: [join(root, 'apps/app/node_modules'), join(root, 'node_modules')], logLevel: 'silent' });
  const { ci, fixtures, commands, slash } = require(out);
  fixtures.selectRepo('Effect-TS/effect');
  const before = JSON.stringify(fixtures.runs);
  const failed = ci.matrixFor('run-4802');
  assert.equal(failed.results.length, 38 * 3);
  assert.equal(new Set(failed.results.map(result => `${result.package}/${result.runtime}`)).size, 114);
  const failure = ci.failureResult(failed);
  assert.equal(failure.package, '@effect/sql-sqlite-bun');
  assert.equal(failure.runtime, 'Bun');
  assert.match(failure.test, /failed deferred commit/);
  assert.match(failure.path, /Client.test.ts$/);
  assert.equal(ci.matrixFor('run-4806').results.filter(result => result.state === 'failure').length, 0);
  assert.equal(ci.matrixFor('run-4806').sharedChecks.find(check => check.stage === 'build').state, 'skipped');
  assert.equal(ci.matrixFor('run-4806').results.filter(result => result.state === 'excluded').length, 18);
  assert.equal(ci.matrixFor('run-4806').results.filter(result => result.state === 'skipped').length, 2);
  assert(ci.matrixFor('run-4805').results.some(result => result.state === 'running'));
  assert(ci.matrixFor('run-4805').results.some(result => result.state === 'queued'));
  assert(!ci.matrixFor('run-4807').results.some(result => result.state === 'success'));
  const missing = ci.matrixFor('run-4806', true);
  assert.equal(missing.state, 'incomplete');
  assert.equal(missing.results.find(result => result.package === '@effect/sql-pg' && result.runtime === 'Deno').state, 'missing');
  assert(!ci.matrixFor(ci.setupRun.id).results.some(result => result.state === 'success'));
  assert(ci.matrixFor(ci.setupRun.id).results.some(result => result.state === 'missing'));
  assert.match(ci.ciRun(ci.setupRun.id).stages[0].log.join('\n'), /ERR_PNPM_OUTDATED_LOCKFILE/);
  assert.equal(JSON.stringify(fixtures.runs), before);
  assert.equal(slash.getSlash('run.affected'), undefined);
  assert.equal(slash.getSlash('run.affected.confirm'), undefined);
  assert.equal(slash.getSlash('ci.job').access, 'public');
  console.log('CI checks passed: 114 cells, failure, exclusions, skipped/missing/running/cancelled/setup states; removed affected commands absent.');
} finally { rmSync(scratch, { recursive: true, force: true }); }
