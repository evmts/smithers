/**
 * The page at https://smithers.sh/migration/1.0, which every 1.0 package sends
 * a 0.x project to.
 *
 * One source: `packages/smithers/docs/migration.md`, in the package that owns
 * `smthrs migrate` and the URL (`Unsupported.migrationUrl`). The page is that
 * guide with the removed-command table spliced in at {@link marker}. The table
 * is built from `Unsupported.ts`, so each row says what the CLI's own refusal
 * says and carries the anchor that refusal links.
 *
 * `gen-cli-data.mjs` writes the page and fails `--check` on drift. The render
 * refuses a guide that would leave a CLI anchor without a target, so a removed
 * command cannot ship ahead of its row.
 */

/** Where the table goes in the guide. An HTML comment, so GitHub shows nothing there. */
export const marker = "<!-- generated:removed-commands -->"

/** The guide's source, repository-relative. */
export const guideSource = "packages/smithers/docs/migration.md"

/** The generated page, site-relative. Astro serves it at `/migration/1.0/`. */
export const guidePage = "src/pages/migration/1.0.md"

/** A heading's id, as Astro's Markdown slugs it. */
const slug = (heading) =>
  heading.trim().toLowerCase().replace(/`+/g, "").replace(/[^\p{L}\p{N}\s\-_]/gu, "").replace(/\s+/g, "-")

const cell = (text) => text.replaceAll("|", "\\|")

/**
 * One row per anchor, in the order `Unsupported.ts` declares them, so the link
 * in a refusal lands on the row that lists the spelling that was typed. The
 * second cell is the reason the refusal itself gave, verbatim.
 *
 * @param {{ verbs: ReadonlyArray<{ anchor: string, reason: string, spellings: ReadonlyArray<string> }>, flags: ReadonlyArray<{ anchor: string, reason: string, spellings: ReadonlyArray<string> }>, reservedFlows: { anchor: string, prefix: string } }} removed
 * @returns {{ table: string, anchors: ReadonlyArray<string> }}
 */
export function removedTable(removed) {
  const rows = new Map()
  for (const entry of [...removed.verbs, ...removed.flags]) {
    const row = rows.get(entry.anchor) ?? { spellings: [], reasons: [] }
    rows.set(entry.anchor, row)
    row.spellings.push(...entry.spellings)
    if (!row.reasons.includes(entry.reason)) row.reasons.push(entry.reason)
  }
  const lines = [...rows].map(([anchor, row]) =>
    `| <a id="${anchor}"></a>${row.spellings.map((spelling) => `\`${cell(spelling)}\``).join(", ")} | ${cell(row.reasons.join(". "))} |`
  )
  const flows = removed.reservedFlows
  lines.push(
    `| <a id="${flows.anchor}"></a>a flow id under \`${flows.prefix}\` | reserved, with no body to run; name a flow from \`smthrs flow list\` |`
  )
  return {
    table: ["| Removed | What the CLI answers |", "| --- | --- |", ...lines].join("\n"),
    anchors: [...rows.keys(), flows.anchor]
  }
}

/**
 * The site page for the guide.
 *
 * @param {string} source the text of {@link guideSource}
 * @param {Parameters<typeof removedTable>[0] & { anchors: ReadonlyArray<string> }} removed the removal table `gen-cli-data.mjs` builds
 * @returns {string}
 */
export function renderMigrationPage(source, removed) {
  const frontmatter = /^---\n([\s\S]*?)\n---\n/.exec(source)
  if (frontmatter === null) throw new Error(`${guideSource} has no frontmatter`)
  const field = (name) => {
    const value = new RegExp(`^${name}:\\s*"(.*)"\\s*$`, "m").exec(frontmatter[1])?.[1]
    if (!value) throw new Error(`${guideSource} needs a quoted ${name}`)
    return value
  }
  const body = source.slice(frontmatter[0].length)
  if (body.split(marker).length !== 2) throw new Error(`${guideSource} must contain ${marker} exactly once`)
  const { table, anchors } = removedTable(removed)
  const headings = [...body.replace(/```[\s\S]*?```/g, "").matchAll(/^#{2,6}\s+(.+)$/gm)].map((match) => slug(match[1]))
  const ids = [...headings, ...anchors]
  const repeated = ids.filter((id, index) => ids.indexOf(id) !== index)
  if (repeated.length > 0) throw new Error(`${guideSource}: a heading and a removed command share the id ${repeated.join(", ")}`)
  const missing = removed.anchors.filter((anchor) => !ids.includes(anchor))
  if (missing.length > 0) {
    throw new Error(`${guideSource} has no heading for #${missing.join(", #")}, which the CLI links at ${removed.migrationUrl ?? "the guide"}`)
  }
  return [
    "---",
    `# GENERATED by apps/site/scripts/gen-cli-data.mjs. Edit ${guideSource}.`,
    "layout: ../../layouts/Guide.astro",
    `title: ${JSON.stringify(field("title"))}`,
    `description: ${JSON.stringify(field("description"))}`,
    "---",
    ""
  ].join("\n") + body.replace(marker, table)
}
