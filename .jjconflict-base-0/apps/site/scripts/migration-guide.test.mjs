/** The migration guide page: one source, every CLI anchor present, nothing shadowed. */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"
import { marker, removedTable, renderMigrationPage } from "./migration-guide.mjs"

const removed = {
  migrationUrl: "https://smithers.sh/migration/1.0",
  verbs: [
    { anchor: "replay", reason: "use `smthrs runs replay`", spellings: ["smthrs replay"] },
    { anchor: "worktrees", reason: "use `smthrs runs fork`", spellings: ["smthrs worktrees list", "smthrs worktrees prune"] }
  ],
  flags: [{ anchor: "ui", reason: "replaced by `smthrs serve`|gone", spellings: ["smthrs up --serve"] }],
  reservedFlows: { anchor: "flows", prefix: "system/" },
  anchors: ["flows", "replay", "run-data", "ui", "worktrees"]
}
const source = `---\ntitle: "Upgrade from 0.x to 1.0"\ndescription: "Guide."\n---\n\nIntro.\n\n## Run data\n\nText.\n\n${marker}\n`

test("one row per anchor, carrying the reason the refusal gave", () => {
  const { table, anchors } = removedTable(removed)
  assert.deepEqual(anchors, ["replay", "worktrees", "ui", "flows"])
  assert.match(table, /\| <a id="worktrees"><\/a>`smthrs worktrees list`, `smthrs worktrees prune` \| use `smthrs runs fork` \|/)
  assert.match(table, /replaced by `smthrs serve`\\\|gone/, "a pipe in a reason is escaped, not a new cell")
})

test("the page is the source with the table spliced in and generated frontmatter", () => {
  const page = renderMigrationPage(source, removed)
  assert.match(page, /^---\n# GENERATED by apps\/site\/scripts\/gen-cli-data\.mjs\. Edit packages\/smithers\/docs\/migration\.md\.\nlayout: \.\.\/\.\.\/layouts\/Guide\.astro\ntitle: "Upgrade from 0\.x to 1\.0"\n/)
  assert.ok(!page.includes(marker))
  assert.match(page, /## Run data[\s\S]*<a id="replay"><\/a>/)
})

test("refuses a guide that leaves a CLI anchor without a target", () => {
  assert.throws(() => renderMigrationPage(source.replace("## Run data", "## Run state"), removed), /no heading for #run-data/)
})

test("refuses a guide without the marker, or with a heading that collides with a removed command", () => {
  assert.throws(() => renderMigrationPage(source.replace(marker, ""), removed), /exactly once/)
  assert.throws(() => renderMigrationPage(source.replace("## Run data", "## Run data\n\n## Replay"), removed), /share the id replay/)
})

test("the committed guide carries every anchor the CLI links and the run-data section", () => {
  const page = readFileSync(new URL("../src/pages/migration/1.0.md", import.meta.url), "utf8")
  const table = JSON.parse(readFileSync(new URL("../src/data/removed-commands.json", import.meta.url), "utf8"))
  assert.match(page, /^## Run data$/m)
  for (const anchor of table.anchors.filter((anchor) => anchor !== "run-data")) assert.ok(page.includes(`<a id="${anchor}"></a>`), anchor)
  for (const removed of ["umbrella import", "JSX authoring", "The `<UI>` element", "0.x run databases"]) assert.ok(page.includes(removed), removed)
  for (const agent of ["ClaudeCodeAgent", "CodexAgent", "OpenCodeAgent"]) assert.ok(page.includes(`| \`${agent}\``), agent)
})

test("no redirect shadows the guide", () => {
  const rules = readFileSync(new URL("../public/_redirects", import.meta.url), "utf8").split("\n")
    .filter((line) => line.trim() && !line.trim().startsWith("#")).map((line) => line.trim().split(/\s+/)[0])
  assert.ok(!rules.some((source) => /^\/migration\/1\.0\/?$/.test(source) || source === "/migration/*" || source === "/*"))
})
